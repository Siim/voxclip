#!/usr/bin/env python3
"""Build shared/caption-styles/casemap.json from UnicodeData.txt (simple case mappings).

    curl -o /tmp/voxclip-ucd/UnicodeData.txt https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
    /tmp/voxclip-captions-venv/bin/python -I tools/captions/build_casemap.py /tmp/voxclip-ucd/UnicodeData.txt

Both apps apply this table instead of String.uppercased() / ToUpperInvariant(), which disagree
(doc/spec/captions.md section 3.4).
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "shared", "caption-styles", "casemap.json")
UNICODE_VERSION = "16.0.0"


def main(path):
    data = open(path, "rb").read()
    upper, lower = [], []
    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        if fields[12]:
            upper.append([cp, int(fields[12], 16)])
        if fields[13]:
            lower.append([cp, int(fields[13], 16)])
    doc = {
        "casemapVersion": 1,
        "unicodeVersion": UNICODE_VERSION,
        "source": "https://www.unicode.org/Public/%s/ucd/UnicodeData.txt" % UNICODE_VERSION,
        "sourceSha256": hashlib.sha256(data).hexdigest(),
        "license": "Unicode-3.0",
        "copyright": "Copyright \u00a9 1991-2024 Unicode, Inc. Derived from the Unicode Character Database under the Unicode License v3; the full notice is in THIRD_PARTY_NOTICES.md.",
        "description": "Simple (1:1) case mappings from UnicodeData.txt fields 12 and 13, plus the explicit rules below. Code points not listed map to themselves. Generated by tools/captions/build_casemap.py.",
        "rules": [
            {"transform": "uppercase", "languages": "*", "from": [0x00DF], "to": [0x0053, 0x0053], "note": "German sharp s becomes SS (capital sharp s U+1E9E is missing from most caption fonts)"},
            {"transform": "uppercase", "languages": ["tr", "az"], "from": [0x0069], "to": [0x0130], "note": "dotted i becomes dotted capital I"},
            {"transform": "lowercase", "languages": ["tr", "az"], "from": [0x0049], "to": [0x0131], "note": "capital I becomes dotless i"},
            {"transform": "lowercase", "languages": ["tr", "az"], "from": [0x0130], "to": [0x0069], "note": "dotted capital I becomes i"},
        ],
        "upper": upper,
        "lower": lower,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("{\n")
        keys = list(doc.keys())
        for i, k in enumerate(keys):
            sep = "," if i < len(keys) - 1 else ""
            if k in ("upper", "lower"):
                body = ",".join("[%d,%d]" % (a, b) for a, b in doc[k])
                f.write('  "%s": [%s]%s\n' % (k, body, sep))
            else:
                f.write("  %s: %s%s\n" % (json.dumps(k), json.dumps(doc[k], ensure_ascii=False), sep))
        f.write("}\n")
    print("wrote", os.path.relpath(OUT, REPO), len(upper), "upper,", len(lower), "lower")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
