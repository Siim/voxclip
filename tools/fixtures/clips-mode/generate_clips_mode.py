#!/usr/bin/env python3
"""Shared vectors for Claude mode's settings (doc/design.md section 6.6): clips.mode, clips.autopilot.count and
clips.autopilot.capUSD. Both Cores replay every case: a valid settings file loads, reads back the expected mode,
count and cap, and saves the three keys unchanged; an invalid one is refused. The settings schema validates each
document here too.

    python3 -I tools/fixtures/clips-mode/generate_clips_mode.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "shared/fixtures/clips-mode/clips-mode-settings-cases.json"


def settings(**values):
    document = {"schema": "voxclip-settings/1"}
    document.update(values)
    return document


def main():
    valid = [
        {"name": "not chosen reads the defaults", "settings": settings(),
         "expect": {"mode": None, "count": 3, "capUSD": 2}},
        {"name": "claude with the defaults written", "settings": settings(**{"clips.mode": "claude", "clips.autopilot.count": 3, "clips.autopilot.capUSD": 2}),
         "expect": {"mode": "claude", "count": 3, "capUSD": 2}},
        {"name": "claude top 5 up to $5", "settings": settings(**{"clips.mode": "claude", "clips.autopilot.count": 5, "clips.autopilot.capUSD": 5}),
         "expect": {"mode": "claude", "count": 5, "capUSD": 5}},
        {"name": "claude top 1 with no spend", "settings": settings(**{"clips.mode": "claude", "clips.autopilot.count": 1, "clips.autopilot.capUSD": 0}),
         "expect": {"mode": "claude", "count": 1, "capUSD": 0}},
        {"name": "pick keeps its count and cap", "settings": settings(**{"clips.mode": "pick", "clips.autopilot.count": 5, "clips.autopilot.capUSD": 1}),
         "expect": {"mode": "pick", "count": 5, "capUSD": 1}},
        {"name": "beside other keys", "settings": settings(**{"clips.mode": "pick", "cache.limitGB": 10, "general.appearance": "dark"}),
         "expect": {"mode": "pick", "count": 3, "capUSD": 2}},
    ]
    invalid = [
        {"name": "unknown mode", "settings": settings(**{"clips.mode": "auto"})},
        {"name": "mode is not a string", "settings": settings(**{"clips.mode": True})},
        {"name": "null mode", "settings": settings(**{"clips.mode": None})},
        {"name": "count 2", "settings": settings(**{"clips.autopilot.count": 2})},
        {"name": "count as text", "settings": settings(**{"clips.autopilot.count": "3"})},
        {"name": "cap 3", "settings": settings(**{"clips.autopilot.capUSD": 3})},
        {"name": "cap with cents", "settings": settings(**{"clips.autopilot.capUSD": 2.5})},
        {"name": "negative cap", "settings": settings(**{"clips.autopilot.capUSD": -1})},
        {"name": "cap as text", "settings": settings(**{"clips.autopilot.capUSD": "2.00"})},
    ]
    document = {
        "schema": "voxclip-clips-mode-settings-cases/1",
        "description": "Claude mode settings (design.md 6.6). Generated by tools/fixtures/clips-mode/generate_clips_mode.py; do not edit by hand. Both Cores replay every case.",
        "valid": valid,
        "invalid": invalid,
        "caseCount": len(valid) + len(invalid),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    try:
        import jsonschema
    except ImportError:
        return
    schema = json.loads((ROOT / "shared/schemas/settings.schema.json").read_text(encoding="utf-8"))
    validator = jsonschema.Draft202012Validator(schema)
    for case in valid:
        errors = list(validator.iter_errors(case["settings"]))
        if errors:
            raise SystemExit(f"{case['name']}: the settings schema refuses a valid case: {errors[0].message}")
    for case in invalid:
        if validator.is_valid(case["settings"]):
            raise SystemExit(f"{case['name']}: the settings schema accepts an invalid case")


if __name__ == "__main__":
    main()
