#!/usr/bin/env python3
"""Write llm-send-cost-cases.json: how an LLM send presents its cost, for every connector in the catalog and every
CLI sign-in state (voice-lab.md section 3.1, LLM sends, as amended by the user's decision of 2026-10-31).

An independent reference of the rule, keyed on the catalog's `group` rather than on either Core's switch: a `local`
connector (loopback or remote local server, Apple on-device) and a `cli` connector signed in on a plan cost nothing
extra and are inline with no amount; an `apiKey` connector, a `cli` connector signed in with an API key and a `cli`
connector whose sign-in is unknown confirm with the unknown-price sentence. Standard library only; two runs give
identical bytes. See shared/fixtures/voice-lab/llm-send-cost-README.md."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CATALOG = ROOT / 'shared/catalog/llm-providers.json'
OUT = ROOT / 'shared/fixtures/voice-lab/llm-send-cost-cases.json'

# Whose pricing a CLI's API key follows: the vendors ai.md section 4.8 names in the CLI consent copy.
CLI_VENDORS = {'claude-code': 'Anthropic', 'codex': 'OpenAI'}
SIGN_INS = ['plan', 'apiKey', None]


def expected(group, sign_in, provider_name):
    if group == 'local' or (group == 'cli' and sign_in == 'plan'):
        return {'kind': 'inline', 'text': ''}
    if group in ('apiKey', 'cli'):
        return {'kind': 'confirm', 'text': f"VoxClip can't tell what this costs. Check {provider_name}'s pricing."}
    raise ValueError(f'unknown connector group {group!r}')


connectors = json.loads(CATALOG.read_text(encoding='utf-8'))['connectors']
cases = []
for connector in connectors:
    identifier, group = connector['id'], connector['group']
    provider_name = CLI_VENDORS[identifier] if group == 'cli' else connector['label']
    for sign_in in SIGN_INS:
        cases.append({'id': f"{identifier}-{sign_in or 'unknown'}", 'connector': identifier, 'group': group,
                      'signIn': sign_in, 'providerName': provider_name,
                      'expected': expected(group, sign_in, provider_name)})

fixture = {
    'schema': 'voxclip-voice-lab-llm-send-cost-cases/1',
    'source': "doc/spec/voice-lab.md §3.1, LLM sends, as amended by the user's decision of 2026-10-31",
    'description': 'Every connector in shared/catalog/llm-providers.json with each CLI sign-in state. Generated by '
                   'tools/fixtures/voice-lab/generate_llm_send_cost.py; see llm-send-cost-README.md.',
    'cases': cases,
}
OUT.write_text(json.dumps(fixture, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
