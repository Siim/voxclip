#!/usr/bin/env python3
"""Generate the shared face-facing vectors (ADR-R48, doc/spec/ai.md section 19.2).

Writes shared/fixtures/clip-frames/face-facing-cases.json (format voxclip-face-facing-cases/1), a new file of its own so no
existing replay changes. Vision's revision-3 face detector gives continuous yaw and pitch. A face faces the camera when
|yaw| <= 0.35 rad and its pitch is within 0.35 rad of the recording's typical pitch (the median pitch of the faces in the
whole video's frame pass), so camera height never counts as looking away. `baseline` cases give the pitches of a pass
(null: a frame without a face or a pitch) and the median; `facing` cases give one face's yaw and pitch (null: not
reported), the baseline (null: judged from 0) and the answer (null: neither angle reported). Swift FaceFacingVectorTests
replays every case; the Windows twin owes the replay. Deterministic and pure IEEE arithmetic (one subtraction and one
mean), so byte-exact; run from anywhere.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DESTINATION = ROOT / 'shared/fixtures/clip-frames/face-facing-cases.json'
YAW_LIMIT = 0.35
PITCH_LIMIT = 0.35


def baseline(pitches):
    values = sorted(value for value in pitches if value is not None)
    if not values:
        return None
    middle = len(values) // 2
    return values[middle] if len(values) % 2 == 1 else (values[middle - 1] + values[middle]) / 2


def facing(yaw, pitch, pitch_baseline):
    measured = False
    if yaw is not None:
        measured = True
        if abs(yaw) > YAW_LIMIT:
            return False
    if pitch is not None:
        measured = True
        if abs(pitch - (pitch_baseline if pitch_baseline is not None else 0)) > PITCH_LIMIT:
            return False
    return True if measured else None


def generated():
    baselines = [
        ('odd-count-takes-the-middle', [0.1, 0.5, 0.2]),
        ('even-count-takes-the-mean-of-the-middle-two', [0.25, 0.0, 0.125, 0.5]),
        ('frames-without-a-pitch-are-skipped', [None, 0.06, None, 0.17, 0.12]),
        ('camera-below-the-eyes', [-0.31, -0.25, -0.4, -0.28, -0.3]),
        ('no-pitch-gives-none', [None, None]),
        ('empty-pass-gives-none', []),
    ]
    facings = [
        ('level-at-the-baseline', 0.0, 0.17, 0.17),
        ('camera-height-pitch-faces-against-its-baseline', 0.05, 0.45, 0.45),
        ('camera-height-pitch-judged-from-zero-does-not', 0.05, 0.45, None),
        ('tilted-down-past-the-limit', 0.0, 0.85, 0.45),
        ('tilted-up-past-the-limit', 0.0, -0.25, 0.17),
        ('tilted-within-the-limit', 0.0, 0.42, 0.17),
        ('yaw-within-the-limit', 0.3, 0.17, 0.17),
        ('yaw-past-the-limit-left', -0.4, 0.17, 0.17),
        ('yaw-past-the-limit-right', 0.57, 0.17, 0.17),
        ('yaw-at-the-limit', 0.35, 0.17, 0.17),
        ('yaw-only', 0.1, None, 0.17),
        ('yaw-only-past-the-limit', 0.785, None, None),
        ('pitch-only', None, 0.3, 0.1),
        ('no-angles-gives-none', None, None, 0.17),
    ]
    return {
        'format': 'voxclip-face-facing-cases/1',
        'description': 'Faces the camera: |yaw| <= yawLimit and |pitch - pitchBaseline| <= pitchLimit (radians; a null '
                       'baseline judges pitch from 0). The baseline is the median pitch of the faces in the whole video\'s '
                       'frame pass. Generated by tools/fixtures/clip-frames/generate_face_facing.py.',
        'yawLimit': YAW_LIMIT,
        'pitchLimit': PITCH_LIMIT,
        'baseline': [{'id': identity, 'pitches': pitches, 'expect': baseline(pitches)} for identity, pitches in baselines],
        'facing': [{'id': identity, 'yaw': yaw, 'pitch': pitch, 'pitchBaseline': base, 'expect': facing(yaw, pitch, base)}
                   for identity, yaw, pitch, base in facings],
    }


def main():
    DESTINATION.write_text(json.dumps(generated(), indent=2) + '\n')


if __name__ == '__main__':
    main()
