#!/usr/bin/env python3
"""Build the Mac clip grade kernels (looks spec 2026-11-28, section 5.10) into the Swift source the app embeds.

apps/macos/Sources/VoxClipMedia/Pipeline/ClipGradeKernels.ci.metal is Core Image kernel language in Metal. SwiftPM can't pass
Core Image's compiler and linker flags, and hosted macOS runners are virtual machines whose GPU may not support the
dynamic libraries runtime compilation needs, so the library is precompiled here: `metal -fcikernel` (for macOS 26.0 and
later, without fast math, read from standard input so no local path lands in the library), then `metallib -cikernel`. The
bytes are written as base64 into ClipGradeKernelLibrary.swift beside the source, with the source's SHA-256, which
ClipGradeKernelTests checks so a library built from older source fails the tests. The shared vectors, not these bytes,
are the test of what the kernels compute.

Needs Xcode's Metal toolchain (`xcodebuild -downloadComponent MetalToolchain`); CI only loads the committed library.
Usage: python3 tools/looks/build_mac_kernels.py [--check]   (--check only compares the source hash; runs anywhere)
"""
import base64
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PIPELINE = ROOT / 'apps/macos/Sources/VoxClipMedia/Pipeline'
SOURCE = PIPELINE / 'ClipGradeKernels.ci.metal'
DESTINATION = PIPELINE / 'ClipGradeKernelLibrary.swift'
MINIMUM_MACOS = '26.0'
LINE = 120


def source_hash():
    return hashlib.sha256(SOURCE.read_bytes()).hexdigest()


def build(directory):
    air, library = Path(directory) / 'kernels.air', Path(directory) / 'kernels.metallib'
    with SOURCE.open('rb') as source:
        subprocess.run(['xcrun', '-sdk', 'macosx', 'metal', '-c', '-fcikernel', '-fno-fast-math',
                        f'-mmacosx-version-min={MINIMUM_MACOS}', '-x', 'metal', '-', '-o', str(air)], stdin=source, check=True)
    subprocess.run(['xcrun', '-sdk', 'macosx', 'metallib', '-cikernel', str(air), '-o', str(library)], check=True)
    version = subprocess.run(['xcrun', '-sdk', 'macosx', 'metal', '--version'], check=True, capture_output=True, text=True)
    return library.read_bytes(), version.stdout.splitlines()[0].strip()


def swift(data, compiler):
    encoded = base64.b64encode(data).decode('ascii')
    lines = '\n'.join('        ' + encoded[i:i + LINE] for i in range(0, len(encoded), LINE))
    return f'''// Generated by tools/looks/build_mac_kernels.py from ClipGradeKernels.ci.metal; do not edit.
// {compiler}; -fcikernel, macOS {MINIMUM_MACOS} and later; {len(data)} bytes.

/// The clip grade's Core Image kernels as a precompiled Metal library (looks spec 2026-11-28, section 5.10).
enum ClipGradeKernelLibrary {{
    /// SHA-256 of ClipGradeKernels.ci.metal when this library was built.
    static let sourceSHA256 = "{source_hash()}"

    static let base64 = """
{lines}
        """
}}
'''


def main():
    if '--check' in sys.argv[1:]:
        text = DESTINATION.read_text() if DESTINATION.exists() else ''
        match = re.search(r'sourceSHA256 = "([0-9a-f]{64})"', text)
        if not match or match.group(1) != source_hash():
            print(f'{DESTINATION.relative_to(ROOT)} is stale: run python3 tools/looks/build_mac_kernels.py', file=sys.stderr)
            return 1
        return 0
    with tempfile.TemporaryDirectory() as directory:
        data, compiler = build(directory)
    text = swift(data, compiler)
    if not DESTINATION.exists() or DESTINATION.read_text() != text:
        DESTINATION.write_text(text)
        print(f'wrote {DESTINATION.relative_to(ROOT)} ({len(data)} bytes)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
